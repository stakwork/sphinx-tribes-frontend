#!/usr/bin/env node

const fs = require('fs');
const path = require('path');

const ROOT_DIR = path.resolve(__dirname, '..');
const SOURCE_DIRS = ['src'];
const DOCS_DIR = path.join(ROOT_DIR, 'docs');
const REGISTRY_PATH = path.join(DOCS_DIR, 'data-testid-registry.md');
const DUPLICATES_PATH = path.join(DOCS_DIR, 'data-testid-duplicates.json');
const VALID_EXTENSIONS = new Set(['.js', '.jsx', '.ts', '.tsx']);
const SKIPPED_DIRS = new Set(['.git', 'node_modules', 'build', 'coverage', 'dist']);

const args = new Set(process.argv.slice(2));
const shouldUpdate = args.has('--update');
const shouldCheck = args.has('--check') || !shouldUpdate;

function toPosixPath(filePath) {
  return path.relative(ROOT_DIR, filePath).split(path.sep).join('/');
}

function walk(dir, files = []) {
  if (!fs.existsSync(dir)) {
    return files;
  }

  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (!SKIPPED_DIRS.has(entry.name)) {
        walk(path.join(dir, entry.name), files);
      }
      continue;
    }

    if (VALID_EXTENSIONS.has(path.extname(entry.name)) && !isTestFile(path.join(dir, entry.name))) {
      files.push(path.join(dir, entry.name));
    }
  }

  return files;
}

function isTestFile(filePath) {
  const normalizedPath = filePath.split(path.sep).join('/');
  const fileName = path.basename(filePath);

  return (
    normalizedPath.includes('/__tests__/') ||
    normalizedPath.includes('/__test__/') ||
    /\.spec\.[jt]sx?$/.test(fileName) ||
    /\.test\.[jt]sx?$/.test(fileName)
  );
}

function getLineColumn(text, offset) {
  const before = text.slice(0, offset);
  const lines = before.split(/\r?\n/);

  return {
    line: lines.length,
    column: lines[lines.length - 1].length + 1
  };
}

function classifyAttribute(match) {
  const [, , doubleQuoted, singleQuoted, expressionDouble, expressionSingle, templateLiteral, expression] =
    match;
  const staticValue = doubleQuoted || singleQuoted || expressionDouble || expressionSingle;

  if (staticValue !== undefined) {
    return { kind: 'static', value: staticValue };
  }

  if (templateLiteral !== undefined) {
    if (!templateLiteral.includes('${')) {
      return { kind: 'static', value: templateLiteral };
    }

    return {
      kind: 'dynamic',
      value: templateLiteral.replace(/\$\{[^}]+\}/g, '*')
    };
  }

  return {
    kind: 'dynamic',
    value: expression.replace(/\s+/g, ' ').trim()
  };
}

function scanDataTestIds() {
  const files = SOURCE_DIRS.flatMap((dir) => walk(path.join(ROOT_DIR, dir))).sort();
  const entries = [];
  const attrRegex =
    /(^|[^\w[\]-])data-testid\s*=\s*(?:"([^"]*)"|'([^']*)'|\{\s*"([^"]*)"\s*\}|\{\s*'([^']*)'\s*\}|\{\s*`([^`]*)`\s*\}|\{([^}]*)\})/g;

  for (const file of files) {
    const text = fs.readFileSync(file, 'utf8');
    let match;

    while ((match = attrRegex.exec(text)) !== null) {
      const attribute = classifyAttribute(match);
      const location = getLineColumn(text, match.index + match[1].length);

      entries.push({
        kind: attribute.kind,
        value: attribute.value,
        file: toPosixPath(file),
        line: location.line,
        column: location.column
      });
    }
  }

  return entries;
}

function summarizeDuplicates(entries) {
  const ids = new Map();

  for (const entry of entries.filter((item) => item.kind === 'static')) {
    if (!ids.has(entry.value)) {
      ids.set(entry.value, []);
    }
    ids.get(entry.value).push(entry);
  }

  const duplicates = {};

  for (const [id, locations] of ids.entries()) {
    if (locations.length < 2) {
      continue;
    }

    duplicates[id] = locations.reduce((summary, location) => {
      summary[location.file] = (summary[location.file] || 0) + 1;
      return summary;
    }, {});
  }

  return Object.fromEntries(Object.entries(duplicates).sort(([a], [b]) => a.localeCompare(b)));
}

function renderRegistry(entries, duplicates) {
  const staticEntries = entries
    .filter((entry) => entry.kind === 'static')
    .sort((a, b) => a.value.localeCompare(b.value) || a.file.localeCompare(b.file) || a.line - b.line);
  const dynamicEntries = entries
    .filter((entry) => entry.kind === 'dynamic')
    .sort((a, b) => a.value.localeCompare(b.value) || a.file.localeCompare(b.file) || a.line - b.line);
  const uniqueStaticIds = new Set(staticEntries.map((entry) => entry.value));
  const duplicateIds = Object.keys(duplicates);
  const lines = [
    '# data-testid Registry',
    '',
    '<!-- Generated by `node scripts/check-data-testids.js --update`. Do not edit by hand. -->',
    '',
    'This registry tracks static `data-testid` values used in `src/` and records dynamic attributes that cannot be compared exactly. The PR audit fails when duplicate static IDs change without an explicit registry update.',
    '',
    '## Summary',
    '',
    `- Static attributes: ${staticEntries.length}`,
    `- Unique static IDs: ${uniqueStaticIds.size}`,
    `- Duplicate static IDs: ${duplicateIds.length}`,
    `- Dynamic attributes: ${dynamicEntries.length}`,
    '',
    '## Duplicate Static IDs',
    ''
  ];

  if (duplicateIds.length === 0) {
    lines.push('No duplicate static IDs found.', '');
  } else {
    lines.push('| data-testid | Locations |', '| --- | --- |');
    for (const id of duplicateIds) {
      const locations = Object.entries(duplicates[id])
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([file, count]) => `${file}${count > 1 ? ` (${count})` : ''}`)
        .join('<br>');
      lines.push(`| \`${id}\` | ${locations} |`);
    }
    lines.push('');
  }

  lines.push('## Static IDs', '', '| data-testid | Location |', '| --- | --- |');
  for (const entry of staticEntries) {
    lines.push(`| \`${entry.value}\` | ${entry.file}:${entry.line} |`);
  }

  lines.push('', '## Dynamic Attributes', '');

  if (dynamicEntries.length === 0) {
    lines.push('No dynamic `data-testid` attributes found.', '');
  } else {
    lines.push('| Pattern or expression | Location |', '| --- | --- |');
    for (const entry of dynamicEntries) {
      lines.push(`| \`${entry.value.replace(/`/g, '\\`')}\` | ${entry.file}:${entry.line} |`);
    }
    lines.push('');
  }

  while (lines[lines.length - 1] === '') {
    lines.pop();
  }

  return `${lines.join('\n')}\n`;
}

function renderDuplicatesFile(duplicates) {
  return `${JSON.stringify(
    {
      description:
        'Generated by node scripts/check-data-testids.js --update. Existing duplicate data-testid values are tracked here so CI can fail on silent reuse.',
      duplicates
    },
    null,
    2
  )}\n`;
}

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function stableStringify(value) {
  return JSON.stringify(value, Object.keys(value).sort());
}

function validateDuplicates(currentDuplicates) {
  if (!fs.existsSync(DUPLICATES_PATH)) {
    return [`Missing ${toPosixPath(DUPLICATES_PATH)}. Run node scripts/check-data-testids.js --update.`];
  }

  const recorded = readJson(DUPLICATES_PATH).duplicates || {};
  const currentIds = Object.keys(currentDuplicates);
  const recordedIds = Object.keys(recorded);
  const errors = [];

  for (const id of currentIds) {
    if (!recorded[id]) {
      errors.push(`New duplicate data-testid "${id}" was introduced.`);
      continue;
    }

    if (stableStringify(currentDuplicates[id]) !== stableStringify(recorded[id])) {
      errors.push(`Duplicate data-testid "${id}" changed locations or count.`);
    }
  }

  for (const id of recordedIds) {
    if (!currentDuplicates[id]) {
      errors.push(`Recorded duplicate data-testid "${id}" no longer exists. Regenerate the registry.`);
    }
  }

  return errors;
}

function validateRegistry(expectedRegistry) {
  if (!fs.existsSync(REGISTRY_PATH)) {
    return [`Missing ${toPosixPath(REGISTRY_PATH)}. Run node scripts/check-data-testids.js --update.`];
  }

  const existingRegistry = fs.readFileSync(REGISTRY_PATH, 'utf8');
  if (existingRegistry !== expectedRegistry) {
    return ['data-testid registry is out of date. Run node scripts/check-data-testids.js --update.'];
  }

  return [];
}

function main() {
  const entries = scanDataTestIds();
  const duplicates = summarizeDuplicates(entries);
  const registry = renderRegistry(entries, duplicates);
  const duplicatesFile = renderDuplicatesFile(duplicates);

  if (shouldUpdate) {
    fs.mkdirSync(DOCS_DIR, { recursive: true });
    fs.writeFileSync(REGISTRY_PATH, registry);
    fs.writeFileSync(DUPLICATES_PATH, duplicatesFile);
    console.log(`Updated ${toPosixPath(REGISTRY_PATH)}`);
    console.log(`Updated ${toPosixPath(DUPLICATES_PATH)}`);
  }

  if (shouldCheck) {
    const errors = [...validateRegistry(registry), ...validateDuplicates(duplicates)];

    if (errors.length > 0) {
      console.error('data-testid audit failed:');
      for (const error of errors) {
        console.error(`- ${error}`);
      }
      process.exit(1);
    }

    console.log(
      `data-testid audit passed: ${entries.length} attributes, ${
        new Set(entries.filter((entry) => entry.kind === 'static').map((entry) => entry.value)).size
      } unique static IDs, ${Object.keys(duplicates).length} duplicate static IDs tracked.`
    );
  }
}

main();
